function ddmmyyyy(date: string): string {
  const [y, m, d] = date.split('-');
  return `${d ?? ''}/${m ?? ''}/${y ?? ''}`;
}

function source(p: IndexPoint, lang: Lang): string {
  const tx = TEXT[lang];
  if (!p.dof) return '';
  return `[${tx.dof(lang === 'es' ? ddmmyyyy(p.dof.date) : p.dof.date)}](${pointUrl(p)})`;
}

export function exampleMarkdown(lang: Lang): string {
  const tx = TEXT[lang];
  const r = run(README_EXAMPLE);
  const lines: string[] = [];
  lines.push(tx.intro(r), '');
  lines.push(`| ${tx.head.join(' | ')} |`, '|---|---|---|');
  lines.push(`| ${tx.inpc(r.from.key)} | ${indexText(r.from)} | ${source(r.from, lang)} |`);
  lines.push(`| ${tx.inpc(r.to.key)}${tx.latest} | ${indexText(r.to)} | ${source(r.to, lang)} |`);
  lines.push(`| ${tx.factor} | \`${indexText(r.to)} ÷ ${indexText(r.from)} = ${factorText(r.factor)}\` | |`);
  lines.push(
    `| **${tx.updated}** | \`${r.current.formatted} × ${factorText(r.factor)}\` = **${r.updated.formatted}** (${signedPercent(r.rate)}, ${r.increase.formatted}) | |`,
  );
  for (const c of r.cap.readings) {
    const inf = c.inflation;
    const label = inf.reading === 'calendar-year' ? tx.reading1(inf.year ?? 0) : tx.reading2(inf.to.key);
    lines.push(`| ${label} | ${tx.max(percent(inf.reported), c.cap.formatted)} | ${source(inf.to, lang)} |`);
  }
  if (r.proposal && r.cap.proposalVerdict) {
    lines.push(`| ${tx.proposal} | ${r.proposal.newRent.formatted} (${signedPercent(r.proposal.rate)}): **${tx.verdict[r.cap.proposalVerdict]}** | |`);
  }
  lines.push('', tx.others, '');
  lines.push(`| ${tx.othersHead.join(' | ')} |`, '|---|---|---:|');
  const cff = run({ ...README_EXAMPLE, period: 'cff' });
  const cal = run({ ...README_EXAMPLE, period: 'calendar' });
  const udis = run({ ...README_EXAMPLE, index: 'udis', startDate: '2025-11-17', increaseDate: '2026-11-17' });
  lines.push(`| ${tx.conventions.cff} | ${monthShort(cff.from.key, lang)} → ${monthShort(cff.to.key, lang)} | ${cff.updated.formatted} |`);
  lines.push(`| ${tx.conventions.calendar} | ${monthShort(cal.from.key, lang)} → ${monthShort(cal.to.key, lang)} | ${cal.updated.formatted} |`);
  lines.push(`| ${tx.conventions.udis} | ${dateLong(udis.from.key, lang)} (${udis.from.value}) → ${dateLong(udis.to.key, lang)} (${udis.to.value}) | ${udis.updated.formatted} |`);
  const url = `${APP_URL}#${encodeState(README_EXAMPLE)}`;
  lines.push('', `<details><summary>${tx.message}</summary>`, '', '```text');
  lines.push(buildMessage(r, { lang, role: 'tenant', url }));
  lines.push('```', '', '</details>');
  return lines.join('\n');
}

export function extractBlock(doc: string): string | null {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) return null;
  return doc.slice(a + START.length, b).replace(/^\n/, '').replace(/\n$/, '');
}

export function replaceBlock(doc: string, block: string): string {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error('README example markers not found');
  return `${doc.slice(0, a + START.length)}\n${block}\n${doc.slice(b)}`;
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  for (const lang of ['en', 'es'] as const) {
    const block = exampleMarkdown(lang);
    if (process.argv.includes('--write')) {
      const file = README_FILES[lang];
      writeFileSync(file, replaceBlock(readFileSync(file, 'utf8'), block));
      console.log(`updated ${file}`);
    } else {
      console.log(`---- ${lang}\n${block}\n`);
    }
  }
}
