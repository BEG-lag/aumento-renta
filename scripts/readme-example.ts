/**
 * Generates the worked example shown in README.md and README.es.md from the
 * code itself, so every number in the docs comes from running it.
 *
 *   node scripts/readme-example.ts           print both blocks
 *   node scripts/readme-example.ts --write   rewrite the blocks in the READMEs
 *
 * test/readme.test.ts fails if the READMEs drift from this output. The
 * example only uses values that are already published, so a data refresh
 * never changes it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { calculate, type UpdateInput, type UpdateResult } from '../src/core/calculate.ts';
import { dateLong, factorText, indexText, monthName, monthShort, percent, pointUrl, signedPercent, type Lang } from '../src/core/format.ts';
import { buildMessage } from '../src/core/message.ts';
import { InpcSeries, UdisSeries } from '../src/core/series.ts';
import { encodeState } from '../src/core/share.ts';
import type { IndexPoint } from '../src/core/series.ts';
import type { InpcData, UdisData } from '../src/data/types.ts';

const ROOT = resolve(import.meta.dirname, '..');
export const README_FILES: Record<Lang, string> = { en: resolve(ROOT, 'README.md'), es: resolve(ROOT, 'README.es.md') };
const START = '<!-- example:start (generated by scripts/readme-example.ts, do not edit) -->';
const END = '<!-- example:end -->';
const APP_URL = 'https://beg-lag.github.io/aumento-renta/';

export const README_EXAMPLE: UpdateInput = {
  amount: '12000',
  index: 'inpc',
  startDate: '2025-12-01',
  increaseDate: '2026-12-01',
  period: 'published',
  location: 'cdmx',
  use: 'housing',
  proposal: { kind: 'percent', value: '8' },
};

function load(): { inpc: InpcSeries; udis: UdisSeries } {
  const inpc = JSON.parse(readFileSync(resolve(ROOT, 'data/inpc.json'), 'utf8')) as InpcData;
  const udis = JSON.parse(readFileSync(resolve(ROOT, 'data/udis.json'), 'utf8')) as UdisData;
  return { inpc: new InpcSeries(inpc), udis: new UdisSeries(udis) };
}

function run(input: UpdateInput): UpdateResult {
  const r = calculate(input, load());
  if (!r.ok) throw new Error(`README example failed: ${r.errors.join(', ')}`);
  return r;
}

